using System;
using ProductionBottlenecks;
using SuperFantasyKingdom;
using SuperFantasyKingdom.Buildings;
using SuperFantasyKingdom.Weather;

int count = 0;
void Check(string name, bool passed)
{
    if (!passed) throw new Exception(name);
    count++;
}
void Expect(BuildingCity building, string expected, string scenario) =>
    Check(scenario, ProductionStatus.Read(building, sprite => "<sprite name=\"" + sprite.name + "\">") == expected);

var bakery = new BuildingCrafting { Output = ResourceType.None, Possible = 0, Missing = ResourceType.Flour };
bakery.Recipes.Add(new CraftingRecipe { product = ResourceType.Bread });
int bread = (int)ResourceType.Bread;
bakery.Storage.Capacity[bread] = 3;
Expect(bakery, "No worker assigned", "disabled worker slot");
bakery.Possible = 1;
Expect(bakery, "Needs Flour", "assignment exposes second blocker");
bakery.Storage.Stored[bread] = 3;
Expect(bakery, "Output storage full", "selected recipe determines output");
bakery.Working = 1;
Expect(bakery, null, "active worker suppresses stale warnings");
bakery.Working = 0;
bakery.Storage.Stored[bread] = 2;
bakery.Storage.Announced[bread] = 1;
Expect(bakery, null, "worker left but batch is still running");
bakery.Storage.Announced[bread] = 0;
Expect(bakery, "Needs Flour", "storage cleared");
bakery.Missing = ResourceType.None;
Expect(bakery, null, "production can resume");
bakery.Sign.gameObject.activeInHierarchy = true;
Expect(bakery, "Idle", "visible native sign with no known cause");
bakery.Sign.enabled = false;
Expect(bakery, null, "disabled native sign");
bakery.Weather = WeatherTypes.Storm;
Expect(bakery, "Waiting for better weather", "weather restriction");
bakery.Weather = WeatherTypes.None;
bakery.CurrentRecipe = -1;
Expect(bakery, null, "no recipe");
bakery.Size = BuildingSize.Small;
bakery.Specialist = true;
bakery.EnabledSlot = false;
Expect(bakery, "No worker assigned", "small building uses specialist toggle");
bakery.EnabledSlot = true;
bakery.Possible = 0;
Expect(bakery, null, "active specialist independent of ordinary slot count");
Expect(new BuildingGeneratingg { Possible = 0 }, null, "automatic production");
Expect(new BuildingDemand { Possible = 0 }, null, "empty production queue");
var yard = new BuildingCity { Working = 2, Inside = 1, Missing = ResourceType.Tree };
yard.Sign.gameObject.activeInHierarchy = true;
Expect(yard, "Needs <sprite name=\"TreeSprite\"> Tree", "visible shortage with other workers on site");
Check("unregistered atlas icon falls back to the resource name", ProductionStatus.Read(yard, sprite => null) == "Needs Tree");
yard.Sign.gameObject.activeInHierarchy = false;
Expect(yard, null, "active gatherer without visible warning");

var processor = new BuildingCrafting { Producer = false, Processor = true, Missing = ResourceType.Flour };
var recipe = new CraftingRecipe { product = ResourceType.Bread, ingredients = new[] { new ResourceAmount(ResourceType.Flour, 4) } };
processor.Recipes.Add(recipe);
int flour = (int)ResourceType.Flour;
processor.Storage.Capacity[flour] = 12;
processor.Storage.Stored[flour] = 1;
Expect(processor, "Needs 3 Flour", "live recipe shortfall without an icon");
recipe.ingredients[0] = new ResourceAmount(ResourceType.Flour, 6);
Expect(processor, "Needs 5 Flour", "modded ingredient amount changes in place");
processor.CurrentRecipe = 1;
Expect(processor, "Needs Flour", "unknown selected recipe has no guessed amount");
processor.Recipes.Add(new CraftingRecipe { ingredients = new[] { new ResourceAmount(ResourceType.Tree, 2) } });
Expect(processor, "Needs Flour", "off-recipe requirement keeps the native shortage");
processor.CurrentRecipe = 0;
processor.Storage.Stored[flour] = 6;
Expect(processor, "Needs Flour", "custom shortage with sufficient local stock has no fabricated count");

var demand = new BuildingDemand { Missing = ResourceType.Tree };
demand.Recipes.Add(recipe);
demand.Recipes.Add(new CraftingRecipe { ingredients = new[] { new ResourceAmount(ResourceType.Tree, 3) } });
demand.Queue.Add(1);
demand.Storage.Capacity[(int)ResourceType.Tree] = 8;
Expect(demand, "Needs 3 <sprite name=\"TreeSprite\"> Tree", "live head of demand queue");
demand.Crafting = true;
Expect(demand, null, "active queue without a sign");
demand.Sign.gameObject.activeInHierarchy = true;
Expect(demand, "Needs <sprite name=\"TreeSprite\"> Tree", "sign during crafting does not claim an input count for the running batch");
demand.Crafting = false;
demand.Queue.Clear();
Expect(demand, "Queue a task", "empty signed demand queue");
recipe.ingredients = new[] { new ResourceAmount(ResourceType.Flour, 4), new ResourceAmount(ResourceType.Flour, 2) };
processor.Recipes[0] = recipe;
processor.Storage.Stored[flour] = 1;
Expect(processor, "Needs Flour", "ambiguous repeated requirements omit the count");
var utility = new BuildingCity { Producer = false };
Expect(utility, null, "unrelated building");
utility.Sign.gameObject.activeInHierarchy = true;
Expect(utility, "Idle", "native sign on a building without a production flag");
utility.Working = 2;
Expect(utility, "Work blocked", "partial blockage does not claim all workers are idle");
utility.Sign.gameObject.activeInHierarchy = false;
Expect(utility, null, "warning clears when eligibility changes");
Expect(new BuildingCity { Outside = true, Possible = 0 }, null, "outside jobs do not use town worker slots");
var generator = new BuildingGeneratingg { Possible = 0, Working = 1, Missing = ResourceType.Flour };
generator.Sign.gameObject.activeInHierarchy = true;
Expect(generator, "Needs Flour", "flagged timed producer");
HoverChecks.Run(Check);
Console.WriteLine($"{count} production-state fixture checks passed.");
